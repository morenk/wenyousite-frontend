import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, expect, test, vi } from "vitest";
import { useConfirmedDelete } from "@/hooks/use-confirmed-delete";
const { confirm } = vi.hoisted(() => ({ confirm: vi.fn() }));
vi.mock("@/components/ui/confirm-provider", () => ({ useConfirm: () => confirm }));
vi.mock("sonner", () => ({ toast: { success: vi.fn(), error: vi.fn() } }));
afterEach(() => { cleanup(); vi.clearAllMocks(); });
const options = { title: "删除评论", description: "删除后无法恢复。", successMessage: "已删除" };
test("确认和请求期间重复触发只删除一次，完成后可再次操作", async () => {
  let accept!: (value: boolean) => void;
  let finish!: () => void;
  confirm.mockImplementationOnce(() => new Promise<boolean>((resolve) => { accept = resolve; }));
  const remove = vi.fn(() => new Promise<void>((resolve) => { finish = resolve; }));
  const { result } = renderHook(useConfirmedDelete);
  let operation!: Promise<void>;
  act(() => { operation = result.current.run(options, remove); void result.current.run(options, remove); });
  expect(confirm).toHaveBeenCalledTimes(1);
  expect(remove).not.toHaveBeenCalled();
  await act(async () => { accept(true); });
  act(() => { void result.current.run(options, remove); });
  expect(remove).toHaveBeenCalledTimes(1);
  expect(result.current.pending).toBe(true);
  await act(async () => { finish(); await operation; });
  expect(result.current.pending).toBe(false);
});
test("确认期间卸载不会发送删除；请求成功后业务完成回调不因缓存移除卸载而丢失", async () => {
  let accept!: (value: boolean) => void;
  confirm.mockImplementationOnce(() => new Promise<boolean>((resolve) => { accept = resolve; }));
  const remove = vi.fn();
  const first = renderHook(useConfirmedDelete);
  let operation!: Promise<void>;
  act(() => { operation = first.result.current.run(options, remove); });
  first.unmount();
  await act(async () => { accept(true); await operation; });
  expect(remove).not.toHaveBeenCalled();
  confirm.mockResolvedValueOnce(true);
  let finish!: () => void;
  remove.mockImplementationOnce(() => new Promise<void>((resolve) => { finish = resolve; }));
  const deleted = vi.fn();
  const second = renderHook(useConfirmedDelete);
  await act(async () => { operation = second.result.current.run(options, remove, deleted); });
  second.unmount();
  await act(async () => { finish(); await operation; });
  expect(deleted).toHaveBeenCalledTimes(1);
});
